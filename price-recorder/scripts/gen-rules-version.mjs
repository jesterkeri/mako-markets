// Writes src/rules-version.ts: RULES_VERSION = sha256 over RULES_REV (src/rules.ts), the resolver's decoder file and
// both feed tables (CHARTS_DS_PLAN 3.3). A change to any of them moves the version, so stored minutes built under
// the old rules are recognised as such. `--check` only compares and exits 1 if the committed file is out of date
// (CI and `pnpm bundle` run it; test/rules-version.test.ts recomputes the same value inside the test runtime).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const rev = /export const RULES_REV = '([^']+)';/.exec(readFileSync(join(root, 'src/rules.ts'), 'utf8'))?.[1];
if (!rev) throw new Error('RULES_REV not found in src/rules.ts');
const sha = (b) => createHash('sha256').update(b).digest('hex');
const parts = ['../cf-worker/src/datastreams.ts', '../cf-worker/src/crypto-feeds.json', '../cf-worker/src/rwa-feeds.json'].map((p) => sha(readFileSync(join(root, p))));
const version = sha([rev, ...parts].join('\n'));
const body = `// GENERATED by scripts/gen-rules-version.mjs: do not edit. sha256 over RULES_REV, cf-worker/src/datastreams.ts,
// cf-worker/src/crypto-feeds.json and cf-worker/src/rwa-feeds.json (CHARTS_DS_PLAN 3.3).
export const RULES_VERSION = '${version}';
`;
const out = join(root, 'src/rules-version.ts');
if (process.argv.includes('--check')) {
  let cur = '';
  try {
    cur = readFileSync(out, 'utf8');
  } catch {}
  if (cur !== body) {
    console.error('src/rules-version.ts is out of date: run `pnpm rules-version` and commit it');
    process.exit(1);
  }
  console.log(`rules version ok: ${version}`);
} else {
  writeFileSync(out, body);
  console.log(`rules version: ${version}`);
}
